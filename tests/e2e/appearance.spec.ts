import { expect, test } from '@playwright/test'

test('appearance persists without discarding a running test or changing its text', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Words mode', exact: true }).click()
  const targets = await page.locator('[data-target]').evaluateAll(words => words.map(word => word.getAttribute('data-target')))
  const input = page.getByRole('textbox', { name: 'Typing input' })
  await input.pressSequentially(targets[0]!.slice(0, 2))
  const correct = await page.locator('[data-state="correct"]').count()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Light', exact: true }).click()
  await page.getByRole('button', { name: '34 pixels', exact: true }).click()
  await page.getByRole('checkbox', { name: /^Live WPM/ }).check()
  await page.getByRole('checkbox', { name: /^Live accuracy/ }).check()
  await page.getByRole('checkbox', { name: /^Reduce motion/ }).check()
  await expect(page.getByRole('checkbox', { name: /^Smooth caret/ })).toBeDisabled()
  await page.getByRole('button', { name: 'Close settings' }).press('Escape')
  await expect(page.getByRole('button', { name: 'Settings', exact: true })).toBeFocused()
  await expect(page.getByTestId('typing-test')).toHaveAttribute('data-status', 'running')
  expect(await page.locator('[data-target]').evaluateAll(words => words.map(word => word.getAttribute('data-target')))).toEqual(targets)
  expect(await page.locator('[data-state="correct"]').count()).toBe(correct)
  await expect(page.getByTestId('live-wpm')).toBeVisible()
  await expect(page.getByTestId('live-accuracy')).toHaveText('100.0%')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await expect(page.getByTestId('typing-caret')).toHaveCSS('transition-duration', '0s')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await expect(page.locator('html')).toHaveAttribute('data-font-size', '34')
  await expect(page.getByTestId('live-wpm')).toHaveText('—')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: /^Reduce motion/ })).toBeChecked()
  await page.getByRole('button', { name: 'Close settings' }).click()
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await expect(page.getByTestId('history-count')).toHaveText('0')
})

test('system reduced motion takes precedence and the settings dialog traps keyboard focus', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: /^Smooth caret/ })).toBeDisabled()
  await expect(page.getByText('Your system’s reduced-motion setting is active.')).toBeVisible()
  await page.getByRole('button', { name: 'Close settings' }).focus()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('checkbox', { name: /^Live accuracy/ })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Close settings' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Settings', exact: true })).toBeFocused()
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: /^Smooth caret/ })).toBeEnabled()
})

