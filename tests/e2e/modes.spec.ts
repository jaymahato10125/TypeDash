import { expect, test } from '@playwright/test'

test('all presets are selectable and mode-specific lengths are remembered', async ({ page }) => {
  await page.goto('/')
  for (const seconds of [15, 30, 60, 120]) {
    await page.getByRole('button', { name: `${seconds} seconds`, exact: true }).click()
    await expect(page.getByTestId('timer')).toHaveText(`${seconds}s`)
  }
  await page.getByRole('button', { name: 'Words mode', exact: true }).click()
  for (const count of [10, 25, 50, 100]) {
    await page.getByRole('button', { name: `${count} words`, exact: true }).click()
    await expect(page.getByTestId('word-progress')).toHaveText(`0/ ${count} words`)
  }
  await page.getByRole('button', { name: 'Time mode', exact: true }).click()
  await expect(page.getByRole('button', { name: '120 seconds', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Words mode', exact: true }).click()
  await expect(page.getByRole('button', { name: '100 words', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('a modified word test finishes without a trailing space and retry preserves settings', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('button', { name: 'Words mode', exact: true }).click()
  await page.getByRole('button', { name: '10 words', exact: true }).click()
  await page.getByRole('button', { name: 'Punctuation', exact: true }).click()
  await page.getByRole('button', { name: 'Numbers', exact: true }).click()
  const targets = await page.locator('[data-target]').evaluateAll(words => words.map(word => word.getAttribute('data-target')!))
  expect(targets).toHaveLength(10)
  expect(targets.some(word => /\d/.test(word))).toBe(true)
  expect(targets.some(word => /[,.?!]/.test(word))).toBe(true)
  const input = page.getByRole('textbox', { name: 'Typing input' })
  await input.pressSequentially(targets.slice(0, -1).join(' ') + ' ')
  await page.clock.fastForward(5000)
  await input.pressSequentially(targets.at(-1)!)
  await expect(page.getByTestId('typing-test')).toHaveAttribute('data-status', 'finished')
  await expect(page.getByTestId('result-accuracy')).toHaveText('100.0%')
  await expect(page.getByTestId('result-configuration')).toHaveText('english / words 10 / punctuation + numbers')
  await page.getByRole('button', { name: 'Retry same text' }).click()
  await expect(page.getByRole('button', { name: '10 words', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Punctuation', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Numbers', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(await page.locator('[data-target]').evaluateAll(words => words.map(word => word.getAttribute('data-target')!))).toEqual(targets)
  await page.getByRole('button', { name: 'Restart test' }).click()
  await expect(page.getByTestId('typing-test')).toHaveAttribute('data-status', 'ready')
  await expect(page.getByRole('button', { name: 'Punctuation', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('changing a running timed test to words abandons its deadline', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('button', { name: '15 seconds', exact: true }).click()
  await page.getByRole('textbox', { name: 'Typing input' }).pressSequentially('x')
  await page.getByRole('button', { name: 'Words mode', exact: true }).click()
  await page.clock.fastForward(15_000)
  await expect(page.getByTestId('typing-test')).toHaveAttribute('data-status', 'ready')
  await expect(page.locator('[data-state="incorrect"], [data-state="correct"], [data-state="extra"]')).toHaveCount(0)
  await page.getByRole('textbox', { name: 'Typing input' }).pressSequentially('x')
  await page.clock.fastForward(120_000)
  await expect(page.getByTestId('typing-test')).toHaveAttribute('data-status', 'running')
})

test('the focus overlay recovers input and does not pause a timed test', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('button', { name: '15 seconds', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Focus typing area' })).toBeVisible()
  await page.getByRole('button', { name: 'Focus typing area' }).click()
  const input = page.getByRole('textbox', { name: 'Typing input' })
  await expect(input).toBeFocused()
  await expect(page.getByRole('button', { name: 'Focus typing area' })).toHaveCount(0)
  await input.pressSequentially('x')
  // Selecting the active preset leaves the run intact but takes keyboard focus.
  await page.getByRole('button', { name: '15 seconds', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Focus typing area' })).toBeVisible()
  await expect(page.getByText('The timer keeps running.', { exact: true })).toBeVisible()
  await page.clock.fastForward(5000)
  await page.getByRole('button', { name: 'Focus typing area' }).click()
  await expect(input).toBeFocused()
  await expect(page.getByTestId('typing-test')).toHaveAttribute('data-status', 'running')
  await page.clock.fastForward(10_000)
  await expect(page.getByTestId('typing-test')).toHaveAttribute('data-status', 'finished')
  await expect(page.getByTestId('result-time')).toHaveText('15s')
})
