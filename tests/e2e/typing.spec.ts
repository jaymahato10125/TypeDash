import { expect, test } from '@playwright/test'

test('a complete timed test preserves a corrected error, then retries the same words', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  const firstWord = await page.locator('[data-target]').first().getAttribute('data-target')
  if (!firstWord) throw new Error('No first word was generated.')
  const input = page.getByRole('textbox', { name: 'Typing input' })
  await input.pressSequentially(firstWord)
  await input.pressSequentially('!')
  await expect(page.locator('[data-state="extra"]')).toHaveCount(1)
  await input.press('Backspace')
  await expect(page.locator('[data-state="extra"]')).toHaveCount(0)
  await page.clock.fastForward(30_000)
  await expect(page.getByTestId('typing-test')).toHaveAttribute('data-status', 'finished')
  const expectedWpm = Math.round(firstWord.length / 5 / 0.5)
  await expect(page.getByTestId('result-wpm')).toHaveText(String(expectedWpm))
  const expectedAccuracy = (firstWord.length / (firstWord.length + 1) * 100).toFixed(1)
  await expect(page.getByTestId('result-accuracy')).toHaveText(`${expectedAccuracy}%`)
  await expect(page.getByRole('heading', { name: 'Your rhythm, in numbers.' })).toBeFocused()
  await page.getByRole('button', { name: 'Retry same text' }).click()
  await expect(page.getByTestId('typing-test')).toHaveAttribute('data-status', 'ready')
  await expect(page.locator('[data-target]').first()).toHaveAttribute('data-target', firstWord)
  await expect(page.getByTestId('timer')).toHaveText('30s')
})

test('restart cancels the old run and remains keyboard accessible', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  const input = page.getByRole('textbox', { name: 'Typing input' })
  await input.pressSequentially('x')
  await page.clock.fastForward(5000)
  await input.press('Tab')
  await expect(page.getByRole('button', { name: 'Restart test' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('typing-test')).toHaveAttribute('data-status', 'ready')
  await page.clock.fastForward(60_000)
  await expect(page.getByTestId('typing-test')).toHaveAttribute('data-status', 'ready')
  await expect(page.getByTestId('timer')).toHaveText('30s')
})

test('an open dialog does not pause the timer', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('textbox', { name: 'Typing input' }).pressSequentially('a')
  await page.getByRole('button', { name: 'About TypeDash', exact: true }).click()
  await page.clock.fastForward(30_000)
  await expect(page.getByTestId('typing-test')).toHaveAttribute('data-status', 'finished')
  await page.getByRole('button', { name: 'Close about panel' }).click()
  await expect(page.getByRole('heading', { name: 'Your rhythm, in numbers.' })).toBeVisible()
})
