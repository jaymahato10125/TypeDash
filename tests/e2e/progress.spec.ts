import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function finishWordTest(page: Page) {
  const targets = await page.locator('[data-target]').evaluateAll(words => words.map(word => word.getAttribute('data-target')!))
  const input = page.getByRole('textbox', { name: 'Typing input' })
  await input.pressSequentially(targets.slice(0, -1).join(' ') + ' ')
  await page.clock.fastForward(1000)
  await input.pressSequentially(targets.at(-1)!)
  await expect(page.getByTestId('typing-test')).toHaveAttribute('data-status', 'finished')
  return targets
}

test('settings, a completed result, and its graph survive reload', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('button', { name: '120 seconds', exact: true }).click()
  await page.getByRole('button', { name: 'Words mode', exact: true }).click()
  await page.getByRole('button', { name: '10 words', exact: true }).click()
  await page.getByRole('button', { name: 'Punctuation', exact: true }).click()
  await page.getByRole('button', { name: 'Numbers', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: '10 words', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Punctuation', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Numbers', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Time mode', exact: true }).click()
  await expect(page.getByTestId('timer')).toHaveText('120s')
  await page.getByRole('button', { name: 'Words mode', exact: true }).click()
  await finishWordTest(page)
  await expect(page.getByTestId('save-status')).toContainText('Saved on this device')
  await expect(page.getByTestId('speed-chart')).toBeVisible()
  await page.getByRole('slider', { name: 'Inspect speed chart time' }).press('Home')
  await expect(page.getByTestId('chart-readout')).toContainText('0.0s')
  await page.reload()
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await expect(page.getByTestId('history-count')).toHaveText('1')
  await page.getByTestId('history-result').first().click()
  await expect(page.getByRole('dialog').getByRole('heading', { level: 3 })).toBeFocused()
  await expect(page.getByRole('dialog').getByTestId('speed-chart')).toBeVisible()
  await page.getByRole('button', { name: '← Back to history' }).click()
  await expect(page.getByTestId('history-result').first()).toBeFocused()
})

test('retry bests stay separate and inspecting results cannot duplicate a completion', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('button', { name: 'Words mode', exact: true }).click()
  await page.getByRole('button', { name: '10 words', exact: true }).click()
  const original = await finishWordTest(page)
  await expect(page.getByTestId('save-status')).toContainText('New personal best')
  await page.getByRole('button', { name: 'Retry same text', exact: true }).click()
  expect(await page.locator('[data-target]').evaluateAll(words => words.map(word => word.getAttribute('data-target')!))).toEqual(original)
  await finishWordTest(page)
  await expect(page.getByTestId('save-status')).toContainText('New retry best')
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await expect(page.getByTestId('history-count')).toHaveText('2')
  await page.getByRole('button', { name: 'Personal bests', exact: true }).click()
  await expect(page.getByTestId('history-best')).toHaveCount(2)
  await page.getByRole('button', { name: 'Close history', exact: true }).click()
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await expect(page.getByTestId('history-count')).toHaveText('2')
})

test('malformed saved data recovers to usable defaults and an empty history', async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('typedash.preferences', '{broken')
    localStorage.setItem('typedash.progress', '{broken')
  })
  await page.goto('/')
  await expect(page.getByTestId('timer')).toHaveText('30s')
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await expect(page.getByTestId('history-count')).toHaveText('0')
  await expect(page.getByRole('dialog').getByText('Some saved history could not be read. Valid results are still available.')).toBeVisible()
  await page.getByRole('button', { name: 'Close history', exact: true }).click()
  await page.getByRole('button', { name: '15 seconds', exact: true }).click()
  await expect(page.getByTestId('timer')).toHaveText('15s')
})

test('blocked browser storage keeps completed results available for the visit', async ({ page }) => {
  await page.addInitScript(() => { Object.defineProperty(window, 'localStorage', { get() { throw new DOMException('Access denied', 'SecurityError') } }) })
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('button', { name: 'Words mode', exact: true }).click()
  await page.getByRole('button', { name: '10 words', exact: true }).click()
  await finishWordTest(page)
  await expect(page.getByTestId('save-status')).toContainText('Kept for this visit')
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await expect(page.getByTestId('history-count')).toHaveText('1')
})
